package coreJavaMaylearn;

public class Lab027 {
    public static void main(String[] args) {
        // Ternary operator.
// ? if true do this : ele do that
        int result = 10>40 ? 89 : 91; // 89 refers true 91 refers false
        System.out.println(result);
        int a1 = (30>40) ? 10: 20;
        System.out.println(a1);

        String str = 10<40 ? "10" : "Eleven";
        System.out.println(str);
    }
}
