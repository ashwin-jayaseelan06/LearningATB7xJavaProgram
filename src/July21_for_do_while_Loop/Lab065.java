public class Lab065 {
    public static void main(String[] args) {
        // print odd and even number till 50
       for(int i=0;i<50;i++){
           if(i%2==0){
               System.out.println("Even->"+i);
           }else {
               System.out.println("Odd ->"+i);
           }

       }
    }}

